function recipe(
  id: string,
  name: string,
  description: string,
  prep: number,
  cook: number,
  season: string,
  protein: string,
  starch: string,
  style: string,
  raw: string,
  steps: string,
  light = true,
): Recipe {
  const list = ingredients(raw);
  const image =
    style === "soupe"
      ? "soup"
      : starch === "pâtes"
        ? "pasta"
        : protein === "poisson"
          ? "fish"
          : style === "salade"
            ? "salad"
            : ["gratin", "tarte"].includes(style)
              ? "bake"
              : protein === "végétarien"
                ? "vegetables"
                : "stew";
  return {
    id,
    name,
    description,
    preparationTime: prep,
    cookingTime: cook,
    totalTime: prep + cook,
    difficulty: prep > 25 ? "Intermédiaire" : "Facile",
    image: `/images/${image}.svg`,
    ingredients: list,
    instructions: steps.split("|"),
    categories: [protein, style, starch].filter((x) => x !== "aucun"),
    seasons: seasons[season],
    months: months[season],
    allergens: Object.entries(allergenWords)
      .filter(([allergen, words]) =>
        list.some(
          (i) =>
            !(allergen === "lait" && normalize(i.name) === "lait de coco") &&
            words.some((w) => normalize(i.name).includes(w)),
        ),
      )
      .map(([allergen]) => allergen),
    childFriendly: true,
    vegetarian: protein === "végétarien",
    servings: 4,
    protein,
    starch,
    style,
    light,
    createdAt: "2026-10-05T00:00:00.000Z",
    updatedAt: "2026-10-05T00:00:00.000Z",
  };
}
