// Format compact du catalogue : nom / quantité / unité / rayon. Quantités pour 4 adultes.
function ingredients(raw: string): Ingredient[] {
  return raw.split(";").map((s) => {
    const [name, quantity, unit, category] = s.split("/");
    return {
      name,
      quantity: Number(quantity),
      unit,
      category: categoryNames[Number(category)],
    };
  });
}
